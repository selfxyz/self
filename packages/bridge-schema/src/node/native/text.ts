/** The lower-case words of a wire value: `USER_CANCELLED`, `react-native` and `userPresence` have two each. */
export function wordsOf(value: string): string[] {
  const words = value
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(word => word.length > 0)
    .map(word => word.toLowerCase());
  if (words.length === 0 || /^[0-9]/.test(words[0])) {
    throw new Error(`No identifier can be made from the value "${value}"`);
  }
  return words;
}

export function wrap(text: string, width: number): string[] {
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(/\s+/).filter(part => part.length > 0)) {
    if (line !== '' && line.length + 1 + word.length > width) {
      lines.push(line);
      line = word;
    } else {
      line = line === '' ? word : `${line} ${word}`;
    }
  }
  if (line !== '') {
    lines.push(line);
  }
  return lines;
}

/** Fails when two values of one enum give the same native name. */
export function requireDistinct(
  enumName: string,
  names: readonly string[],
): void {
  const repeated = names.find((name, index) => names.indexOf(name) !== index);
  if (repeated !== undefined) {
    throw new Error(`${enumName}: two values give the name ${repeated}`);
  }
}

export function joinFile(sections: readonly (readonly string[])[]): string {
  return `${sections.map(section => section.join('\n')).join('\n\n')}\n`;
}
